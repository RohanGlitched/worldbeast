// Copies the pure game core (and the shared wire types) into the world actor, which can only
// import files from its own directory. src/ stays the single source of truth: never edit the copies.
import { mkdirSync, readFileSync, writeFileSync, readdirSync, unlinkSync, existsSync } from "node:fs";
import { dirname, join, relative, posix } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const actor = join(root, "base44/actors/world");
const copies = [
  ["src/core/rng.ts", "core/rng.ts"],
  ["src/core/titan.ts", "core/titan.ts"],
  ["src/core/field.ts", "core/field.ts"],
  ["src/core/hunt.ts", "core/hunt.ts"],
  ["src/net/types.ts", "shared/types.ts"],
  ["src/net/pathcodec.ts", "shared/pathcodec.ts"],
];
// where each "@/x/y" module lands inside the actor
const aliasTarget = Object.fromEntries(copies.map(([src, dst]) => [src.replace(/^src\//, "@/").replace(/\.ts$/, ""), dst]));

const header = (src) => `// GENERATED by scripts/sync-core.mjs from ${src}. Do not edit; edit the source and run npm run sync-core.\n`;

for (const dir of ["core", "shared"]) {
  const d = join(actor, dir);
  mkdirSync(d, { recursive: true });
  for (const f of readdirSync(d)) if (f.endsWith(".ts")) unlinkSync(join(d, f));
}

for (const [src, dst] of copies) {
  let code = readFileSync(join(root, src), "utf8");
  const dstDir = posix.dirname(dst);
  code = code.replace(/(from\s+|import\s*\(\s*)(["'])([^"']+)\2/g, (m, pre, q, spec) => {
    let target;
    if (spec.startsWith("@/")) {
      const hit = aliasTarget[spec.replace(/\.ts$/, "")];
      if (!hit) throw new Error(`${src}: import ${spec} is not synced into the actor; add it to scripts/sync-core.mjs`);
      target = posix.relative(dstDir, hit);
      if (!target.startsWith(".")) target = "./" + target;
    } else if (spec.startsWith(".")) {
      target = spec.endsWith(".ts") ? spec : spec + ".ts";
      const resolved = posix.join(posix.dirname(src), target);
      if (!existsSync(join(root, resolved))) throw new Error(`${src}: relative import ${spec} not found`);
      if (!copies.some(([s]) => s === resolved)) throw new Error(`${src}: imports ${resolved}, which is not synced into the actor`);
    } else {
      throw new Error(`${src}: bare import "${spec}" cannot run inside the actor`);
    }
    return `${pre}${q}${target}${q}`;
  });
  const out = join(actor, dst);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, header(src) + code);
  console.log(`synced ${src} -> ${relative(root, out).replace(/\\/g, "/")}`);
}
